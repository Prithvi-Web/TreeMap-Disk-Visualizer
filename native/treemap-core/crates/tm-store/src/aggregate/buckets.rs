/// The bucket JavaScript's `bucketFor` puts `bytes` in: 0 for a size of 0 or less, and
/// otherwise how many bucket starts `bytes` has reached.
pub fn size_bucket(bytes: f64) -> usize {
    // JavaScript's `bytes <= 0` is false for NaN, whose bucket would then be NaN and count
    // nowhere; the walk hands on no NaN size (a withheld entry's is 0), and here it would
    // land in bucket 0.
    if bytes.is_nan() || bytes <= 0.0 {
        return 0;
    }
    SIZE_BUCKET_STARTS.partition_point(|&start| f64::from_bits(start) <= bytes)
}
