//! The size histogram's buckets (design §S.6.1; `computeSizeDistribution` in
//! `src/services/reclaimInputs.ts`): sixteen per octave across 64 octaves, a file of `bytes`
//! in bucket `floor(log2(bytes) × 16)`, clamped to 0..1024, and every size of 0 or less in
//! bucket 0.
//!
//! The bucket is JavaScript's: `Math.log2` as V8 computes it, rounded as V8 rounds it. Rust's
//! `log2` need not round the same way at a bucket's edge, so this module takes nothing from
//! it: [`SIZE_BUCKET_STARTS`] holds the smallest positive double of each bucket from 1 on, as
//! JavaScript found them (bisecting over the doubles' bits), and a size's bucket is how many
//! of those starts it has reached. `tests/sizeBuckets.test.ts` recomputes the table in the
//! running JavaScript and holds this file to it; Node 24.16 and Electron 31.7.7 give the same
//! table, bit for bit (27 Sep 2026).

