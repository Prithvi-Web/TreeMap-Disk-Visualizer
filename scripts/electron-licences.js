'use strict';
/*
 * Electron's and Chromium's licences in the packaged app — scripts/afterPack.js
 * runs this before signing, on every platform.
 *
 * Every Electron release zip carries three files at its root: LICENSE
 * (Electron's, MIT), LICENSES.chromium.html (Chromium's credits: every
 * licence of the code Chromium is built from) and version. On Windows and
 * Linux electron-builder keeps the two licence files beside the executable,
 * LICENSE renamed to LICENSE.electron.txt (app-builder-lib's
 * ElectronFramework.js, cleanupAfterUnpack). On macOS its createMacApp
 * deletes both from the output folder (app-builder-lib/out/electron/
 * electronMac.js, electron-builder 24.13.3), because anything beside the .app
 * would fall out of the dmg and the zip — and nothing puts them inside, so
 * TreeMap.app shipped Electron and Chromium without their licences. There is
 * no hook between the unpacking and that deletion, so afterPack puts them
 * back: into the bundle's Contents/Resources, under the names electron-builder
 * gives them on the other two platforms, before the ad-hoc signature seals
 * the bundle.
 *
 * They are taken from the Electron electron-builder unpacked, and checked
 * against the Electron inside the bundle:
 *   - the source is where electron-builder took Electron from: electronDist's
 *     zip, or electronDist's folder (it copies Electron.app from there, and
 *     the licences sit beside it), or else the release zip itself, through
 *     @electron/get (electron's own dependency) with the electron package's
 *     checksums.json, so the zip is the published one and a cached copy is
 *     verified without the network;
 *   - the zip's version must be the version of the Electron Framework in the
 *     bundle (its Info.plist's CFBundleVersion);
 *   - the licence must be Electron's MIT licence, and the credits Chromium's
 *     generated page, listing at least MIN_CREDITED_PRODUCTS products.
 * Any failure throws, naming the file, and nothing is written.
 *
 * assertElectronLicences then holds every package to the result: the two
 * files, in the bundle's Resources on macOS and beside the executable on
 * Windows and Linux, each passing the same content checks.
 */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

/** Their names in the packaged app: electron-builder's names beside the Windows and Linux executables. */
const LICENCE_FILE = 'LICENSE.electron.txt';
const CREDITS_FILE = 'LICENSES.chromium.html';
/** Their names at the root of an Electron release zip (and of an unpacked Electron folder). */
const ZIP_ENTRY = { licence: 'LICENSE', credits: 'LICENSES.chromium.html', version: 'version' };
/** Fewer products than this is not Chromium's credits page; Electron 31.7.7's lists 410. */
const MIN_CREDITED_PRODUCTS = 100;
/** Generous room above the 9.5 MB credits page of Electron 31.7.7, for `unzip -p` output. */
const ZIP_ENTRY_MAX_BYTES = 256 * 1024 * 1024;

const CREDITS_GENERATOR = '<!-- Generated by licenses.py; do not edit. -->';
const MIT_GRANT = 'Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files';
const MIT_DISCLAIMER = 'THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND';

/** `bytes` as text, every run of white space read as one space and none at either end (a byte-order mark is white space to \s and trim). */
function flattened(bytes) {
  return bytes.toString('utf8').replace(/\s+/g, ' ').trim();
}

/** Null when `bytes` is Electron's MIT licence; otherwise why it is not. */
function checkLicenceText(bytes) {
  const text = flattened(bytes);
  if (text === '') return "Electron's licence is empty";
  const grantAt = text.indexOf(MIT_GRANT);
  // The copyright lines: everything before the grant (or, without one, the opening).
  const holders = grantAt === -1 ? text.slice(0, 200) : text.slice(0, grantAt);
  if (!text.startsWith('Copyright (c) ') || !holders.includes('Electron')) {
    return `Electron's licence must open with Electron's copyright lines; it opens with "${text.slice(0, 60)}"`;
  }
  if (grantAt === -1) return 'Electron\'s licence lacks the MIT grant ("Permission is hereby granted, free of charge, …")';
  if (!text.includes(MIT_DISCLAIMER)) return `Electron's licence lacks the MIT disclaimer ("${MIT_DISCLAIMER}")`;
  return null;
}

/** Null when `bytes` is Chromium's credits page; otherwise why it is not. */
function checkCreditsHtml(bytes) {
  const text = bytes.toString('utf8').trimStart(); // a byte-order mark included
  if (text === '') return "Chromium's credits page is empty";
  if (!text.startsWith(CREDITS_GENERATOR)) return `Chromium's credits page must open with "${CREDITS_GENERATOR}" (Chromium's licenses.py writes it)`;
  if (!text.includes('<title>Credits</title>')) return "Chromium's credits page must be titled <title>Credits</title>";
  const products = (text.match(/class="product"/g) ?? []).length;
  if (products < MIN_CREDITED_PRODUCTS) {
    return `Chromium's credits page lists ${products} products where Chromium's lists at least ${MIN_CREDITED_PRODUCTS}; it is cut off or another page`;
  }
  return null;
}

/** The Info.plist of the Electron Framework inside a macOS app bundle. */
function frameworkPlistOf(app) {
  return path.join(app, 'Contents', 'Frameworks', 'Electron Framework.framework', 'Resources', 'Info.plist');
}

/** The version of the Electron inside the bundle `app`, from its framework's Info.plist; throws naming the file when it cannot tell. */
function bundledElectronVersion(app) {
  const plist = frameworkPlistOf(app);
  let text;
  try {
    text = fs.readFileSync(plist, 'utf8');
  } catch (err) {
    throw new Error(`cannot tell which Electron the bundle holds: ${plist} could not be read (${err.code ?? err.message})`);
  }
  const m = /<key>CFBundleVersion<\/key>\s*<string>([^<]+)<\/string>/.exec(text);
  if (!m) throw new Error(`cannot tell which Electron the bundle holds: ${plist} has no CFBundleVersion`);
  return m[1].trim();
}

/** The release zip's name, as electron-builder's unpack and @electron/get both spell it. */
function electronZipName(version, platform, arch) {
  return `electron-v${version}-${platform}-${arch}.zip`;
}

/**
 * Where electron-builder took Electron from, as a source of its licences:
 * electronDist's zip ({ kind: 'zip' }), electronDist's folder ({ kind: 'dir' }),
 * or the release zip, through `downloadZip`. A setting this step does not
 * follow — electronDist as a function, or any electronDownload — is refused
 * rather than guessed at.
 */
async function licenceSource({ config, projectDir, version, platform, arch }, { downloadZip }) {
  if (config.electronDownload != null) {
    throw new Error('build.electronDownload is set, and this step takes Electron from @electron/get\'s default source; teach scripts/electron-licences.js that setting before using it');
  }
  const dist = config.electronDist;
  if (typeof dist === 'function') {
    throw new Error('build.electronDist is a function, so this step cannot tell which Electron it supplied; give electronDist as a folder');
  }
  if (dist != null) {
    const folder = path.isAbsolute(dist) ? dist : path.resolve(projectDir, dist);
    const zip = path.join(folder, electronZipName(version, platform, arch));
    return fs.existsSync(zip) ? { kind: 'zip', path: zip } : { kind: 'dir', path: folder };
  }
  return { kind: 'zip', path: await downloadZip({ version, platform, arch }) };
}

/** LICENSE, LICENSES.chromium.html and version from `source`: zip entries through `readZipEntry`, or a folder's files. */
function readLicences(source, { readZipEntry: readEntry }) {
  const read = (entry) => {
    if (source.kind === 'zip') {
      try {
        return readEntry(source.path, entry);
      } catch (err) {
        throw new Error(`${entry} could not be read from ${source.path}: ${err.message}`);
      }
    }
    const file = path.join(source.path, entry);
    try {
      return fs.readFileSync(file);
    } catch (err) {
      throw new Error(`${file} could not be read (${err.code ?? err.message})`);
    }
  };
  return { licence: read(ZIP_ENTRY.licence), credits: read(ZIP_ENTRY.credits), version: read(ZIP_ENTRY.version) };
}

/** One entry of `zip`, whole, through `unzip -p` (macOS ships /usr/bin/unzip; only a Mac packages macOS). */
function readZipEntry(zip, entry) {
  try {
    return execFileSync('unzip', ['-p', zip, entry], { maxBuffer: ZIP_ENTRY_MAX_BYTES, stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (err) {
    const how = [err.code, err.status != null ? `exit ${err.status}` : null, err.signal].filter(Boolean).join(', ') || err.message;
    const said = err.stderr ? String(err.stderr).trim() : '';
    throw new Error(`unzip -p ${zip} ${entry} failed (${how})${said ? `: ${said}` : ''}`);
  }
}

/** Whether this process runs under a test runner — the rule src/services/realMachineGuard.ts keeps. */
function underTestRunner(env = process.env) {
  return Boolean(env.TREEMAP_FORBID_REAL_TRASH) || Boolean(env.NODE_TEST_CONTEXT);
}

/**
 * The path of the published Electron zip for `version`, `platform` and
 * `arch`, from @electron/get's cache — verified there against the electron
 * package's checksums.json, offline — or downloaded and verified when the
 * cache has none. The way electron's own postinstall fetches it, so on a
 * machine that ran `npm ci` the zip is already cached. Under a test runner it
 * refuses before it looks anything up: tests pass `downloadZip` instead.
 */
async function downloadElectronZip({ version, platform, arch }) {
  if (underTestRunner()) {
    throw new Error('the Electron zip is not fetched under a test runner; pass downloadZip in its place');
  }
  const electronDir = path.dirname(require.resolve('electron/package.json'));
  const checksums = require(path.join(electronDir, 'checksums.json'));
  const name = electronZipName(version, platform, arch);
  if (!checksums[name]) {
    throw new Error(`the installed electron package (${require(path.join(electronDir, 'package.json')).version}) has no checksum for ${name}, so no zip of it can be verified`);
  }
  const { downloadArtifact } = require(require.resolve('@electron/get', { paths: [electronDir] }));
  return downloadArtifact({ version, artifactName: 'electron', platform, arch, checksums, cacheRoot: process.env.electron_config_cache });
}

/**
 * Puts Electron's LICENSE and Chromium's credits into a macOS bundle's
 * Contents/Resources, from where electron-builder took Electron, after
 * checking all three files. Throws naming the folder, and writes nothing,
 * when any check fails. Answers one line saying what it placed.
 */
async function placeElectronLicences(
  { appOutDir, productFilename, arch, frameworkVersion, config, projectDir },
  { downloadZip = downloadElectronZip, readZipEntry: readEntry = readZipEntry } = {},
) {
  const app = path.join(appOutDir, `${productFilename}.app`);
  const resources = path.join(app, 'Contents', 'Resources');
  const fail = (why) => new Error(`[afterPack] Electron's licences cannot be put in ${resources}: ${why}`);
  let source;
  let files;
  let bundled;
  try {
    bundled = bundledElectronVersion(app);
    source = await licenceSource({ config, projectDir, version: frameworkVersion, platform: 'darwin', arch }, { downloadZip });
    files = readLicences(source, { readZipEntry: readEntry });
  } catch (err) {
    throw fail(err.message);
  }
  const reasons = [];
  const version = files.version.toString('utf8').trim();
  if (version !== bundled) reasons.push(`${source.path} holds Electron ${version || '(no version)'}, but the bundle holds Electron ${bundled}`);
  const licence = checkLicenceText(files.licence);
  if (licence) reasons.push(`${licence} (${source.path})`);
  const credits = checkCreditsHtml(files.credits);
  if (credits) reasons.push(`${credits} (${source.path})`);
  if (reasons.length > 0) throw fail(reasons.join('; '));
  fs.writeFileSync(path.join(resources, LICENCE_FILE), files.licence);
  fs.writeFileSync(path.join(resources, CREDITS_FILE), files.credits);
  return `${LICENCE_FILE} and ${CREDITS_FILE} of Electron ${version}, from ${source.path}`;
}

/** Where the two files belong in a packaged app: the bundle's Resources on macOS, beside the executable elsewhere. */
function licencePlace({ platform, appOutDir, productFilename }) {
  return platform === 'darwin' ? path.join(appOutDir, `${productFilename}.app`, 'Contents', 'Resources') : appOutDir;
}

/** Throws, naming each path, unless the packaged app holds Electron's licence and Chromium's credits where they belong; answers what it found. */
function assertElectronLicences({ platform, appOutDir, productFilename }) {
  const place = licencePlace({ platform, appOutDir, productFilename });
  const reasons = [];
  for (const [name, check] of [[LICENCE_FILE, checkLicenceText], [CREDITS_FILE, checkCreditsHtml]]) {
    const file = path.join(place, name);
    let bytes;
    try {
      bytes = fs.readFileSync(file);
    } catch {
      reasons.push(`${file} does not exist`);
      continue;
    }
    const why = check(bytes);
    if (why) reasons.push(`${file}: ${why}`);
  }
  if (reasons.length > 0) {
    throw new Error(`[afterPack] the ${platform} app does not carry Electron's and Chromium's licences: ${reasons.join('; ')}`);
  }
  return `${path.join(place, LICENCE_FILE)} and ${CREDITS_FILE} beside it`;
}

module.exports = {
  LICENCE_FILE,
  CREDITS_FILE,
  MIN_CREDITED_PRODUCTS,
  checkLicenceText,
  checkCreditsHtml,
  bundledElectronVersion,
  electronZipName,
  licenceSource,
  readLicences,
  readZipEntry,
  downloadElectronZip,
  placeElectronLicences,
  licencePlace,
  assertElectronLicences,
};
