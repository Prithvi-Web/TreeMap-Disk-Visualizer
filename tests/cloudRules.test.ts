test('the committed oracle is what the regexes answer today', () => {
  const committed = fs.readFileSync(ORACLE_PATH, 'utf8');
  const today = oracleText();
  assert.ok(
    committed === today,
    `the oracle is stale: regenerate it with \`npx tsx tests/fixtures/cloudRulesOracle.ts\` and commit it (${committed.length} bytes committed, ${today.length} today)`,
  );
});

test('the oracle holds CLOUD_RULES, every edge case and tens of thousands of paths, and every table answers through the builder as the regexes do', () => {
  const tables = parseOracle(fs.readFileSync(ORACLE_PATH, 'utf8'));
  assert.deepEqual(tables.map((t) => t.name), ['cloudProviderFor', 'probe-letters', 'probe-ends', 'probe-order', 'probe-syntax', 'probe-ligatures']);
  const [production] = tables;
  assert.deepEqual(production.rules, productionRules());
  assert.equal(production.paths.length, EDGE_CASES.length + ORACLE_GENERATED);
  assert.ok(ORACLE_GENERATED >= 20_000);

  EDGE_CASES.forEach((edge, k) => {
    const bytes = typeof edge.path === 'string' ? utf8(edge.path) : edge.path;
    assert.deepEqual(production.paths[k], bytes, edge.why);
    assert.equal(production.expected[k], idOf(edge.expected), edge.why);
  });
  const counts = new Map<number, number>();
  for (const id of production.expected) counts.set(id, (counts.get(id) ?? 0) + 1);
  for (const id of [0, 1, 2, 3]) assert.ok((counts.get(id) ?? 0) >= 1_000, `provider ${id}: ${counts.get(id) ?? 0} paths`);
  const notUtf8 = production.paths.filter((bytes) => !Buffer.from(decodeLikeNode(bytes), 'utf8').equals(Buffer.from(bytes))).length;
  assert.ok(notUtf8 >= 1_000, `${notUtf8} paths are not UTF-8`);

  let checked = 0;
  for (const table of tables) {
    const matchers = cloudMatchers(table.rules);
    const reference = referenceMatcher(table.rules);
    table.paths.forEach((bytes, k) => {
      const text = decodeLikeNode(bytes);
      const where = `${table.name} ${JSON.stringify(text)}`;
      assert.equal(firstMatchingProvider(matchers, text) ?? 0, table.expected[k], where);
      assert.equal(reference(text), table.expected[k], `the reference, ${where}`);
      checked++;
    });
  }
  production.paths.forEach((bytes, k) => {
    assert.equal(idOf(cloudProviderFor(decodeLikeNode(bytes))), production.expected[k], JSON.stringify(decodeLikeNode(bytes)));
  });
  assert.ok(tables.every((t) => t.rules.length > 0 && t.paths.length > 0), 'no table is empty');
  assert.ok(tables[1].paths.length >= 3_000, `${tables[1].paths.length} paths try the letters`);
  assert.equal(checked, tables.reduce((sum, t) => sum + t.paths.length, 0));
});

test('the probes answer as written by hand where a matcher could go wrong', () => {
  const tables = new Map(parseOracle(fs.readFileSync(ORACLE_PATH, 'utf8')).map((t) => [t.name, t]));
  const answer = (name: string, path: string): number => {
    const table = tables.get(name);
    assert.ok(table, name);
    const k = table.paths.findIndex((bytes) => Buffer.from(bytes).equals(Buffer.from(utf8(path))));
    assert.ok(k >= 0, `${name} holds ${JSON.stringify(path)}`);
    return table.expected[k];
  };
  // Every ASCII letter is its own provider: K is 11, i 9, s 19.
  assert.equal(answer('probe-letters', 'K'), 11);
  assert.equal(answer('probe-letters', 'k'), 11);
  assert.equal(answer('probe-letters', '\u212A'), 0, 'KELVIN SIGN is not k');
  assert.equal(answer('probe-letters', '\u0130'), 0, 'U+0130 is not i');
  assert.equal(answer('probe-letters', '\u0131'), 0, 'U+0131 is not i');
  assert.equal(answer('probe-letters', '\u017F'), 0, 'U+017F is not s');
  assert.equal(answer('probe-letters', '\uFF4B'), 0, 'a fullwidth k is not k');
  assert.equal(answer('probe-ends', 'xK'), 1);
  assert.equal(answer('probe-ends', 'x\u212A'), 0);
  assert.equal(answer('probe-ends', 'xk\n'), 0, 'not before a final newline');
  assert.equal(answer('probe-ends', 'kx'), 0, 'an end rule is not an anywhere rule');
  assert.equal(answer('probe-ends', 'ax'), 0, 'a dot is a dot');
  assert.equal(answer('probe-order', 'ba'), 2, 'the first rule wins');
  assert.equal(answer('probe-order', 'axc'), 3, 'the first rule wins, not the first rule of the provider');
  assert.equal(answer('probe-order', 'ca'), 1);
  assert.equal(answer('probe-syntax', 'abc'), 0, 'the dot in a.c is a dot');
  assert.equal(answer('probe-syntax', 'u'), 0, 'the bar in u|v is a bar');
  assert.equal(answer('probe-syntax', 'z1'), 0, 'the backslash in z\\d is a backslash');
  assert.equal(answer('probe-ligatures', '\u00DF'), 0, '\u00DF is not ss');
  assert.equal(answer('probe-ligatures', '\uFB06'), 0, 'the st ligature is not st');
});

test("JavaScript's i flag without u never takes a character outside ASCII for one inside it, over every code point", () => {
  const anyAscii = /[\0-\x7f]/i;
  const anyAsciiUnicode = /[\0-\x7f]/iu;
  const folded: string[] = [];
  const foldedWithU: string[] = [];
  for (let cp = 0x80; cp <= 0x10ffff; cp++) {
    const s = String.fromCodePoint(cp); // a lone surrogate for U+D800-U+DFFF, as a JavaScript string may hold
    if (anyAscii.test(s)) folded.push(hex(cp));
    if ((cp < 0xd800 || cp > 0xdfff) && anyAsciiUnicode.test(s)) foldedWithU.push(hex(cp));
  }
  assert.deepEqual(folded, []);
  assert.deepEqual(foldedWithU, ['U+017F', 'U+212A'], 'the u flag would fold these onto s and k: never add it');
  assert.equal(/k/i.test('\u212A'), false);
  assert.equal(/i/i.test('\u0130'), false);
  assert.equal(/i/i.test('\u0131'), false);
  assert.equal(/s/i.test('\u017F'), false);
  assert.equal(/k/iu.test('\u212A'), true);
  assert.equal(/s/iu.test('\u017F'), true);
});

test('the code points whose JavaScript lower or upper case holds ASCII are pinned (Node 24.16 and Electron 31 agree)', () => {
  const lower: string[] = [];
  const upper: string[] = [];
  const holdsAscii = (s: string): boolean => /[\0-\x7f]/.test(s);
  for (let cp = 0x80; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const s = String.fromCodePoint(cp);
    if (holdsAscii(s.toLowerCase())) lower.push(hex(cp));
    if (holdsAscii(s.toUpperCase())) upper.push(hex(cp));
  }
  assert.deepEqual(lower, ['U+0130', 'U+212A']);
  assert.deepEqual(upper, [
    'U+00DF', 'U+0131', 'U+0149', 'U+017F', 'U+01F0', 'U+1E96', 'U+1E97', 'U+1E98', 'U+1E99', 'U+1E9A',
    'U+FB00', 'U+FB01', 'U+FB02', 'U+FB03', 'U+FB04', 'U+FB05', 'U+FB06',
  ]);
  // So a table matched through toLowerCase() would take U+0130 for i and U+212A for k; the regexes do not.
  for (const [c, letter] of [['\u0130', 'i'], ['\u212A', 'k']]) {
    assert.ok(c.toLowerCase().includes(letter), `${hex(c.charCodeAt(0))} lower-cases to hold ${letter}`);
    assert.equal(new RegExp(letter, 'i').test(c), false, `the regex does not take ${hex(c.charCodeAt(0))} for ${letter}`);
  }
});

