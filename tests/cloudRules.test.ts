test('a table the Rust matcher could not answer as the regexes do is refused', () => {
  // Outside ASCII the i flag folds letters among themselves, which a matcher of ASCII case could not follow.
  assert.equal(/\u00E9/i.test('\u00C9'), true);
  for (const text of ['Caf\u00E9', '', 'a\tb', 'a\nb', '\u212A', 'x\u007F']) {
    assert.throws(() => cloudMatchers([{ provider: 'icloud', text, at: 'anywhere' }]), /printable ASCII/, JSON.stringify(text));
  }
  assert.throws(() => cloudMatchers([{ provider: 'icloud', text: 'x', at: 'start' as never }]), /anywhere or end/);
  assert.doesNotThrow(() => cloudMatchers([{ provider: 'icloud', text: ' ~!"#$%&\'()*+,-./09:;<=>?@AZ[\\]^_`az{|}', at: 'end' }]));
});

test('the oracle file escapes what a tab-separated line cannot hold, and reads back byte for byte', () => {
  const bytes = new Uint8Array([0x41, 0x09, 0x0a, 0x25, 0x20, 0x7f, 0x80, 0xff, 0x20]);
  assert.equal(escapeBytes(bytes), 'A%09%0A%25 %7F%80%FF%20');
  assert.deepEqual(unescapeBytes(escapeBytes(bytes)), bytes);
  assert.throws(() => unescapeBytes('%G1'), /bad escape/);
  assert.throws(() => unescapeBytes('a%4'), /bad escape/);
});
